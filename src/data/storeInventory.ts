function normalizeModel(model: string): string {
  return model
    .toLowerCase()
    .replace(/^iphone\s*/i, '')
    .replace(/\s+/g, '')
    .trim();
}

function normalizeColor(color: string): string {
  const c = color.toLowerCase().trim();
  if (['gray', 'grey', 'cinza', 'titanium', 'grafite'].includes(c)) return 'grey';
  if (['black', 'preto', 'dark', 'midnight'].includes(c)) return 'black';
  if (['pink', 'rosa', 'rose'].includes(c)) return 'pink';
  if (['white', 'branco', 'silver', 'prata'].includes(c)) return 'white';
  if (['orange', 'laranja', 'sunset'].includes(c)) return 'orange';
  return c;
}

/**
 * Checks if a combination is explicitly marked out of stock.
 */
export function isCombinationOutOfStock(model: string, color: string): boolean {
  if (!model || !color) return false;
  const normColor = normalizeColor(color);
  const normModel = normalizeModel(model);

  return OUT_OF_STOCK_COMBINATIONS.some(
    (item) => normalizeColor(item.color) === normColor && normalizeModel(item.model) === normModel
  );
}

/**
 * Checks if a given Model + Color combination is physically present and available in the store's inventory.
 */
export function isVariantInStoreCatalog(model: string, color: string): boolean {
  if (!model || !color) return false;

  // 1. Check explicit out-of-stock list
  if (isCombinationOutOfStock(model, color)) {
    return false;
  }

  const normColor = normalizeColor(color);
  const normModel = normalizeModel(model);

  // 2. Check if present in available store variants
  return STORE_AVAILABLE_VARIANTS.some((v) => {
    return normalizeColor(v.color) === normColor && normalizeModel(v.model) === normModel;
  });
}

/**
 * Returns list of available models for a given color.
 */
export function getAvailableModelsForColor(color: string): string[] {
  const normColor = normalizeColor(color);
  return STORE_AVAILABLE_VARIANTS.filter((v) => normalizeColor(v.color) === normColor).map((v) => v.model);
}

/**
 * Returns list of available colors for a given model.
 */
export function getAvailableColorsForModel(model: string): string[] {
  const normModel = normalizeModel(model);
  return STORE_AVAILABLE_VARIANTS.filter((v) => normalizeModel(v.model) === normModel).map((v) => v.color);
}

